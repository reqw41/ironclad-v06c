; ============================================================================
; disk.asm — дисковая версия (сборка -DDISK, tools/build_disk.sh): картинки 16 цветов с дискеты.
; Картинка на дискете — 32 КБ видеопамяти подряд (4 плоскости, tools/mkdisk.py), читается прямо в
; $8000..$FFFF без буфера. Позиции прошиты при сборке (build/disk/layout.inc, tools/build_fdd.py).
; ============================================================================
            include F_LAYOUT                ; позиции на дискете (build/disk[_en]/layout.inc, tools/build_fdd.py)

FDD_PIC_YIELD equ 0         ; 0 — картинка читается подряд под погашенным экраном (~1.9 с на
                            ; железе, звук на это время молчит: чтение ждёт конца мелодии);
                            ; 1 — между секторами кадр отдаётся прерыванию (музыка и клавиатура
                            ; живут, но на железе ~оборот диска на сектор: ~6 с на картинку)

; DE = позиция картинки (FD_TITLE / FD_VICTORY / FD_DEFEAT). Экран уже погашен (disp_blank):
; сначала кадр — ISR льёт погашенную палитру, пока не кончатся мелодия и шумовой эффект
; (звук не обрывается на полуноте), затем 32 КБ в $8000..$FFFF.
; Выход: NC — картинка на экране; CY — не прочиталась, экран очищен нулями. EI. Портит всё.
disk_pic:
            push de
dk_1:       ei
            halt
            ld   a,(mus_on)
            ld   hl,sfx_t
            or   (hl)
            jp   nz,dk_1
            ld   a,FDD_PIC_YIELD
            ld   (fdd_yld),a
            pop  de
            ld   b,FD_PIC_N
            ld   hl,8000h
dk_rd:      call fdd_read               ; стенд засекает кадры от dk_rd до dk_done
dk_done:    ei
            ret  nc
            call scr_clear_all
            scf
            ret

            include "fdd.asm"
