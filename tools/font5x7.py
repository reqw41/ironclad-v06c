def rows(ch):
    """8 байт знакоместа: бит 7 = левый столбец."""
    g = G.get(ch, G['?'])
    assert len(g) == 7 and all(len(r) == 5 for r in g), ch
    out = []
    for r in g:
        b = 0
        for i, c in enumerate(r):
            if c == '#':
                b |= 0x80 >> i
        out.append(b)
    return out + [0]


# внутренняя кодировка игры: 20h..40h — как ASCII, буквы с 41h по алфавиту, Й — последней
# (тогда 41h+i для i = 0..9 — А Б В Г Д Е Ж З И К, столбцы русского морского боя)
RU_ORDER = 'АБВГДЕЖЗИКЛМНОПРСТУФХЦЧШЩЫЬЭЮЯЙ'


def preview(out, scale=8):
    """PNG: 31 буква (строка 1-2), цифры и знаки (строка 3); сетка точек."""
    import zlib, struct
    lines = [RU_ORDER[:16], RU_ORDER[16:], '0123456789 .,:;-/?!()+=']
    cw, ch = 7 * scale, 10 * scale
    W = max(len(l) for l in lines) * cw + scale * 2
    H = len(lines) * ch + scale * 2
    img = [[(255, 255, 255)] * W for _ in range(H)]
    for li, l in enumerate(lines):
        for ci, c in enumerate(l):
            g = G.get(c)
            if g is None:
                continue
            x0, y0 = scale + ci * cw, scale + li * ch
            for y in range(7):
                for x in range(5):
                    on = g[y][x] == '#'
                    for dy in range(scale):
                        for dx in range(scale):
                            edge = dx == 0 or dy == 0
                            img[y0 + y * scale + dy][x0 + x * scale + dx] = (20, 20, 90) if on else ((215, 215, 215) if edge else (245, 245, 245))
    raw = b''.join(b'\0' + bytes(v for px in row for v in px) for row in img)
    def chunk(t, d):
        return struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    with open(out, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', W, H, 8, 2, 0, 0, 0))
                + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


