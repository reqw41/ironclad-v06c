#!/bin/sh
# Гейт джойстика «П»: каждое направление и обе кнопки дают код клавиши, как с клавиатуры
# (вправо 28, влево 29, вверх 30, вниз 31, огонь 1 — пробел, огонь 2 — ТАБ), а порт 0Eh
# (джойстик «С», на Турбо+ там мусор) в коде не читается. Негативный контроль: при молчащем
# порте 6 (JOYDEAD=1) гейт обязан покраснеть.
#   tools/joyp_gate.sh [образ.rom]      (по умолчанию build/ironclad.rom)
cd "$(dirname "$0")/.."
ROM=${1:-build/ironclad.rom}
run() {
  S="w 300"
  for b in 1 2 4 8 64 128; do S="$S;jd $b;w 2;m kbd_last 1;ju $b;w 4"; done
  node tools/vshot.js "$ROM" "$S" | sed -n 's/^kbd_last ([0-9a-f]*): //p' | tr '\n' ' '
}
check() {
  got=$(run)
  [ "$got" = "1c 1d 1e 1f 20 09 " ]
}
ok=0
if check; then echo "  ok      джойстик «П»: вправо/влево/вверх/вниз/огонь 1/огонь 2 -> $(run)"; else echo "  ПРОВАЛ  джойстик «П»: получено '$(run)', ждали '1c 1d 1e 1f 20 09'"; ok=1; fi
if grep -inE 'in +a, *\((0?0?eh|14)\)' src/*.asm src/*/*.asm >/dev/null 2>&1; then
  echo "  ПРОВАЛ  в коде читается порт 0Eh"; ok=1
else echo "  ok      порт 0Eh не читается"; fi
if JOYDEAD=1 check; then echo "  ПРОВАЛ  негативный контроль: при молчащем порте 6 гейт зелёный"; ok=1
else echo "  ok      негативный контроль: порт 6 молчит — красный, как и должен"; fi
[ $ok = 0 ] && echo "ГЕЙТ ДЖОЙСТИКА «П»: ЗЕЛЁНЫЙ" || { echo "ГЕЙТ ДЖОЙСТИКА «П»: КРАСНЫЙ"; exit 1; }
